#[test]
fn splice_then_remove_restores_original_bytes() {
    for original in [
        "",
        "A\n",
        "A",
        "A\n\n",
        "# T\n\nbody\n",
        "A\r\n",
        "A\r\nB",
        "# T\r\n\r\nbody\r\n",
        "A\r\n\r\n",
    ] {
        let spliced = splice(original, "fact\nline two");
        assert_ne!(spliced, original);
        assert_eq!(remove(&spliced), original, "spliced={spliced:?}");
    }
}

