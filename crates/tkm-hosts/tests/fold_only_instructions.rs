#[test]
fn splice_appends_block_after_existing_content() {
    let original = "# My project\n\nSome docs.\n";
    let result = splice(original, "fact");
    // Original content must be preserved byte-for-byte.
    assert!(
        result.starts_with(original),
        "content before block was changed: original={original:?} result={result:?}"
    );
    assert!(result.contains("<!-- tokenimum:begin -->"));
    assert!(result.contains("fact"));
}

#[test]
fn splice_replaces_existing_block_in_place() {
    let before = "# Docs\n";
    let after = "\n## More\n";
    let initial =
        format!("{before}<!-- tokenimum:begin -->\nold content\n<!-- tokenimum:end -->\n{after}");
    let result = splice(&initial, "new content");
    // bytes before and after the block must be unchanged
    assert!(result.starts_with(before), "prefix changed");
    assert!(result.contains(after), "suffix changed or missing");
    assert!(result.contains("new content"), "new content absent");
    assert!(!result.contains("old content"), "old content still present");
}

#[test]
fn splice_is_idempotent_when_body_unchanged() {
    let body = "same fact\n";
    let once = splice("", body);
    let twice = splice(&once, body);
    assert_eq!(once, twice, "second splice changed the output");
}

#[test]
