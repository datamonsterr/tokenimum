#[test]
fn apply_creates_file_and_excludes_it() {
    let scratch = Scratch::new("apply-create");
    scratch.init_git();
    let opts = ApplyOptions::default();
    let report = apply(&scratch.0, Host::Codex, "fact body", opts).unwrap();
    assert!(!report.dry_run);
    // File must now exist.
    let agents_md = scratch.0.join("AGENTS.md");
    assert!(agents_md.exists(), "AGENTS.md not created");
    let content = fs::read_to_string(&agents_md).unwrap();
    assert!(content.contains("fact body"));
    assert!(content.contains("<!-- tokenimum:begin -->"));
    // .git/info/exclude must reference the file.
    let exclude = scratch.0.join(".git/info/exclude");
    let exclude_text = fs::read_to_string(&exclude).unwrap_or_default();
    assert!(
        exclude_text.lines().any(|l| l == "/AGENTS.md"),
        "AGENTS.md not in .git/info/exclude: {exclude_text:?}"
    );
    assert!(
        exclude_text.lines().any(|l| l == "/AGENTS.md.tkm-bak"),
        "creation marker not excluded: {exclude_text:?}"
    );
    // A .tkm-bak sibling must exist and be empty.
    let bak = scratch.0.join("AGENTS.md.tkm-bak");
    assert!(bak.exists(), ".tkm-bak not created");
    assert_eq!(
        fs::metadata(&bak).unwrap().len(),
        0,
        ".tkm-bak is not empty"
    );
    // changed_files should list the file + backup + exclude.
    assert!(
        report.changed_files.contains(&agents_md),
        "AGENTS.md missing from changed_files"
    );
}

