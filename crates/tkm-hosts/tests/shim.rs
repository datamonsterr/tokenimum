#![forbid(unsafe_code)]
#![allow(clippy::unwrap_used, clippy::expect_used)]
use sha2::{Digest, Sha256};
use std::fmt::Write;
use tkm_hosts::{
    AdapterError,
    shim::{ShimStatus, render, verify_shim},
};
use tkm_proto::Host;

fn hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::new(), |mut out, byte| {
            write!(out, "{byte:02x}").unwrap();
            out
        })
}

fn after_second_line(bytes: &[u8]) -> &[u8] {
    let first = bytes.iter().position(|b| *b == b'\n').unwrap();
    let second = first + 1 + bytes[first + 1..].iter().position(|b| *b == b'\n').unwrap();
    &bytes[second + 1..]
}

#[test]
fn rendered_shims_have_at_most_forty_lines_and_no_placeholders() {
    for host in [Host::Opencode, Host::Pi] {
        let bytes = render(host, "1.2.3").unwrap();
        let text = String::from_utf8(bytes).unwrap();
        assert!(
            text.lines().count() <= 40,
            "{host:?}: {} lines",
            text.lines().count()
        );
        assert!(text.ends_with('\n'));
        assert!(!text.contains("{{"), "{host:?} left a placeholder");
    }
}

#[test]
fn header_names_version_host_and_hash_of_every_byte_after_line_two() {
    for (host, name) in [(Host::Opencode, "opencode"), (Host::Pi, "pi")] {
        let bytes = render(host, "1.2.3").unwrap();
        let text = String::from_utf8(bytes.clone()).unwrap();
        let mut lines = text.lines();
        assert_eq!(
            lines.next().unwrap(),
            format!("// tokenimum 1.2.3 {name} shim. Generated by tkm init; do not edit.")
        );
        assert_eq!(
            lines.next().unwrap(),
            format!("// tokenimum-sha256: {}", hex(after_second_line(&bytes)))
        );
    }
}

#[test]
fn render_is_deterministic_and_version_only_changes_the_first_line() {
    let a = render(Host::Opencode, "1.0.0").unwrap();
    assert_eq!(a, render(Host::Opencode, "1.0.0").unwrap());
    let b = render(Host::Opencode, "2.0.0").unwrap();
    assert_ne!(a, b);
    assert_eq!(after_second_line(&a), after_second_line(&b));
}

#[test]
fn render_rejects_hosts_without_a_shim() {
    assert!(matches!(
        render(Host::Claude, "1.0.0"),
        Err(AdapterError::Unsupported { .. })
    ));
}

#[test]
fn verify_accepts_untouched_shims() {
    for host in [Host::Opencode, Host::Pi] {
        assert_eq!(verify_shim(&render(host, "1.2.3").unwrap()), ShimStatus::Ok);
    }
}

#[test]
fn verify_detects_any_body_edit() {
    let mut bytes = render(Host::Pi, "1.2.3").unwrap();
    let last = bytes.len() - 2;
    bytes[last] ^= 1;
    assert_eq!(verify_shim(&bytes), ShimStatus::HashMismatch);
    let mut appended = render(Host::Pi, "1.2.3").unwrap();
    appended.extend_from_slice(b"// extra\n");
    assert_eq!(verify_shim(&appended), ShimStatus::HashMismatch);
}

#[test]
fn verify_rejects_foreign_or_malformed_headers() {
    for bytes in [
        &b""[..],
        b"export default function () {}\n",
        b"// tokenimum 1.0.0 pi shim. Generated by tkm init; do not edit.\n",
        b"// tokenimum 1.0.0 pi shim. Generated by tkm init; do not edit.\n// tokenimum-sha256: zz\nbody\n",
        b"// someone else's file\n// tokenimum-sha256: 00\n",
        &[0xff, 0xfe, 0x00],
    ] {
        assert_eq!(verify_shim(bytes), ShimStatus::NotOurs, "{bytes:?}");
    }
}

#[test]
fn shims_use_only_type_imports_and_the_documented_commands() {
    let opencode = String::from_utf8(render(Host::Opencode, "1.0.0").unwrap()).unwrap();
    let pi = String::from_utf8(render(Host::Pi, "1.0.0").unwrap()).unwrap();
    for (text, host) in [(&opencode, "opencode"), (&pi, "pi")] {
        for line in text.lines().filter(|line| line.starts_with("import")) {
            assert!(line.starts_with("import type "), "{line}");
        }
        assert!(text.contains("tkm-hook"));
        assert!(text.contains("--host-event"));
        assert!(text.contains(&format!("\"{host}\"")) || text.contains(&format!("--host {host}")));
        assert!(text.contains("3000"));
        assert!(text.contains("1000"));
    }
    assert!(pi.contains("--payload"));
    assert!(pi.contains("pi.exec"));
    assert!(opencode.contains("chat.message"));
    assert!(opencode.contains("showToast"));
}

#[test]
fn opencode_shim_part_id_has_the_prt_prefix_opencode_validates() {
    let text = String::from_utf8(render(Host::Opencode, "1.0.0").unwrap()).unwrap();
    assert!(
        text.contains("\"prt_tkm_\""),
        "part ids must start with prt"
    );
    assert!(!text.contains("\"tkm-\""));
}

#[test]
fn shims_never_let_reply_handling_throw_and_opencode_clears_its_timer() {
    let opencode = String::from_utf8(render(Host::Opencode, "1.0.0").unwrap()).unwrap();
    let pi = String::from_utf8(render(Host::Pi, "1.0.0").unwrap()).unwrap();
    assert!(opencode.contains("clearTimeout"));
    assert!(opencode.contains("100000"), "payload size cap");
    assert!(pi.contains("100000"));
    // Reply application (the part push) sits inside a try block in opencode.
    let push = opencode.find("output.parts.push").unwrap();
    let try_before = opencode[..push].rfind("try {").unwrap();
    let catch_after = opencode[push..].find("catch").unwrap();
    assert!(try_before < push && catch_after > 0);
}
