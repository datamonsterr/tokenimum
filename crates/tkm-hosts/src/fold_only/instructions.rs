//! Instructions-file injection for fold-only mode (SPEC 6.12, ADR 0001 item 9, ADR 0026).
//!
//! Facts live in a marked block of the repository's agent instructions file,
//! between `<!-- tokenimum:begin -->` and `<!-- tokenimum:end -->`. The block is
//! regenerated and never edited by hand; every byte outside it is preserved.
//! When tokenimum creates the file it also writes an empty `<file>.tkm-bak`
//! (ADR 0011's "did not exist" marker) and lists both in `.git/info/exclude`.
//! For an existing file, `<file>.tkm-bak` holds its original bytes instead.

use crate::writer::deny::{exclude_target, refuse_tracked, update_exclude};
use crate::writer::{
    Update, atomic_update, checked_backup, invalid, read_optional, retry_update, safe_target,
    update_with_backup,
};
use crate::{AdapterError, InstallReport};
use std::fs;
use std::path::Path;
use tkm_proto::Host;

const BEGIN: &str = "<!-- tokenimum:begin -->";
const END: &str = "<!-- tokenimum:end -->";
const GENERATED: &str = "<!-- Generated by tokenimum; do not edit this block by hand. -->";

/// Options for applying or removing the block.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct ApplyOptions {
    /// Allow a git-tracked file (config key `inject.instructions_file_tracked`).
    pub allow_tracked: bool,
    /// Compute the change without writing.
    pub dry_run: bool,
}

/// Renders the complete marked block with `\n` line endings and no newline
/// after the end marker. CRLF in `body` is normalised to `\n`.
#[must_use]
pub fn render_block(body: &str) -> String {
    let body = body.replace("\r\n", "\n");
    let separator = if body.is_empty() || body.ends_with('\n') {
        ""
    } else {
        "\n"
    };
    format!("{BEGIN}\n{GENERATED}\n{body}{separator}{END}")
}

/// Marker lines found outside fenced code blocks.
struct Scan {
    /// Byte range of the first complete block, markers included.
    block: Option<(usize, usize)>,
    /// Begin-marker lines outside fences.
    begins: usize,
}

fn fence_of(line: &str) -> Option<char> {
    let line = line.trim_start();
    if line.starts_with("```") {
        Some('`')
    } else if line.starts_with("~~~") {
        Some('~')
    } else {
        None
    }
}

/// A marker counts only alone on its line (trailing whitespace and CR ignored)
/// and outside ``` or ~~~ fences, so prose and examples that quote it are inert.
fn scan(text: &str) -> Scan {
    let mut fence = None;
    let mut offset = 0;
    let mut begin = None;
    let mut block = None;
    let mut begins = 0;
    for raw in text.split_inclusive('\n') {
        let start = offset;
        offset += raw.len();
        let line = raw.strip_suffix('\n').unwrap_or(raw);
        let line = line.strip_suffix('\r').unwrap_or(line);
        if let Some(mark) = fence_of(line) {
            match fence {
                None => fence = Some(mark),
                Some(open) if open == mark => fence = None,
                Some(_) => {}
            }
            continue;
        }
        if fence.is_some() {
            continue;
        }
        let marker = line.trim_end();
        if marker == BEGIN {
            begins += 1;
            begin.get_or_insert(start);
        } else if marker == END
            && block.is_none()
            && let Some(from) = begin
        {
            block = Some((from, start + line.len()));
        }
    }
    Scan { block, begins }
}

fn find_block(text: &str) -> Option<(usize, usize)> {
    scan(text).block
}

/// Checks that the marked block is unambiguous.
///
/// # Errors
/// [`AdapterError::InvalidPayload`] for more than one begin marker, or a begin
/// marker without an end marker.
pub fn validate(existing: &str) -> Result<(), AdapterError> {
    let found = scan(existing);
    if found.begins > 1 {
        return Err(invalid(
            "more than one tokenimum begin marker; fix the file by hand",
        ));
    }
    if found.begins == 1 && found.block.is_none() {
        return Err(invalid("tokenimum block has no end marker; fix it by hand"));
    }
    Ok(())
}

fn eol_of(text: &str) -> &'static str {
    match text.find('\n') {
        Some(index) if text[..index].ends_with('\r') => "\r\n",
        _ => "\n",
    }
}

/// Replaces the existing block in place, or appends one after a blank line.
///
/// The block uses the file's line ending (CRLF if its first line ends in CRLF).
/// Bytes outside the markers are unchanged. A file without a final newline gets
/// a block without one. Use [`validate`] first: with several or unterminated
/// markers only the first complete block is replaced.
#[must_use]
pub fn splice(existing: &str, body: &str) -> String {
    let eol = eol_of(existing);
    let block = render_block(body).replace('\n', eol);
    if let Some((start, end)) = find_block(existing) {
        return format!("{}{block}{}", &existing[..start], &existing[end..]);
    }
    let mut out = existing.to_owned();
    let mut final_newline = true;
    if !out.is_empty() {
        if !out.ends_with('\n') {
            out.push_str(eol);
            final_newline = false;
        }
        out.push_str(eol);
    }
    out.push_str(&block);
    if final_newline {
        out.push_str(eol);
    }
    out
}

/// Removes the block and the separator that [`splice`] added, restoring the
/// original bytes exactly (LF, CRLF, with or without a final newline).
///
/// A block placed by hand loses only its own lines. Returns the input unchanged
/// when there is no complete block.
#[must_use]
pub fn remove(existing: &str) -> String {
    let Some((start, end)) = find_block(existing) else {
        return existing.to_owned();
    };
    let eol = eol_of(existing);
    let blank = format!("{eol}{eol}");
    let before = &existing[..start];
    let rest = &existing[end..];
    let (before, after) = if rest.is_empty() {
        (before.strip_suffix(blank.as_str()).unwrap_or(before), rest)
    } else {
        let after = rest
            .strip_prefix("\r\n")
            .or_else(|| rest.strip_prefix('\n'))
            .unwrap_or(rest);
        let before = if before.ends_with(blank.as_str()) {
            &before[..before.len() - eol.len()]
        } else {
            before
        };
        (before, after)
    };
    format!("{before}{after}")
}

/// Instructions file read by `host`, or `None` when no read of one is verified.
///
/// Claude Code reads `CLAUDE.md`; Codex, Cursor, Kimi Code, Codewhale, opencode
/// and Pi read `AGENTS.md` (evidence in ADR 0026). Antigravity is unverified, so
/// it is report-only.
#[must_use]
pub const fn instructions_file(host: Host) -> Option<&'static str> {
    match host {
        Host::Claude => Some("CLAUDE.md"),
        Host::Codex | Host::Cursor | Host::Kimi | Host::Deepseek | Host::Opencode | Host::Pi => {
            Some("AGENTS.md")
        }
        // `Host` is non-exhaustive: unverified and future harnesses are report-only.
        _ => None,
    }
}

fn report_only(host: Host, dry_run: bool) -> InstallReport {
    InstallReport {
        changed_files: Vec::new(),
        instructions: vec![format!(
            "No verified instructions file for {}; the tokenimum skill or `tkm facts --brief` still work.",
            host.as_str()
        )],
        dry_run,
    }
}

fn guard(
    repo_root: &Path,
    path: &Path,
    target: &Path,
    opts: ApplyOptions,
) -> Result<(), AdapterError> {
    if !opts.allow_tracked {
        refuse_tracked(repo_root, path)?;
        refuse_tracked(repo_root, target)?;
    }
    Ok(())
}

/// Writes or regenerates the tokenimum block in the host's instructions file.
///
/// Refuses a tracked file unless `allow_tracked`, a symlink resolving outside
/// `repo_root`, and ambiguous markers (see [`validate`]). Writes atomically
/// (one retry if the file changed meanwhile), is idempotent, and honours
/// `dry_run`.
///
/// Before the first write, `<file>.tkm-bak` receives the original bytes of an
/// existing file (ADR 0011) or stays empty when tokenimum creates the file.
/// `.git/info/exclude` is updated only after that write succeeded: the file and
/// the backup when created, the backup alone for an existing file.
/// Hosts without a verified file return a report-only result.
///
/// # Errors
/// [`AdapterError::UnsafeTarget`] for refusals, [`AdapterError::InvalidPayload`]
/// for ambiguous markers, otherwise git or I/O failures.
pub fn apply(
    repo_root: &Path,
    host: Host,
    body: &str,
    opts: ApplyOptions,
) -> Result<InstallReport, AdapterError> {
    let Some(name) = instructions_file(host) else {
        return Ok(report_only(host, opts.dry_run));
    };
    let path = repo_root.join(name);
    let target = safe_target(repo_root, &path)?;
    let (marker, marker_target) = checked_backup(repo_root, &path, &target)?;
    retry_update(read_optional(&target)?, |snapshot| {
        guard(repo_root, &path, &target, opts)?;
        if let Some(text) = snapshot {
            validate(text)?;
        }
        let desired = splice(snapshot.unwrap_or_default(), body);
        let mut report = InstallReport {
            dry_run: opts.dry_run,
            ..InstallReport::default()
        };
        if snapshot == Some(desired.as_str()) {
            return Ok(Update::Done(report));
        }
        report.changed_files.push(path.clone());
        let creating = snapshot.is_none();
        // An empty existing file cannot be told apart from the creation marker.
        let backup =
            (snapshot != Some("") && !marker_target.exists()).then_some(marker_target.as_path());
        if backup.is_some() {
            report.changed_files.push(marker.clone());
        }
        if !opts.dry_run {
            match update_with_backup(&target, snapshot, &desired, backup, || {})? {
                Update::Done(()) => {}
                Update::Retry(current) => return Ok(Update::Retry(current)),
            }
        }
        // Only now is it certain that this call wrote the file or its backup.
        let mut lines = Vec::new();
        if creating {
            lines.push(format!("/{name}"));
        }
        if backup.is_some() {
            lines.push(format!("/{name}.tkm-bak"));
        }
        if !lines.is_empty() {
            let exclude = exclude_target(repo_root)?;
            let mut changed = false;
            for line in &lines {
                changed |= update_exclude(&exclude, line, opts.dry_run)?;
            }
            if changed {
                report.changed_files.push(exclude);
            }
        }
        Ok(Update::Done(report))
    })
}

/// Removes the block from the host's instructions file.
///
/// With the empty creation marker, deletes the file and marker when nothing but
/// whitespace remains. With a backup of the original, writes the backup's bytes
/// back and deletes it when the result equals it (ADR 0011); a file the person
/// edited elsewhere keeps its edits and the backup. `.git/info/exclude` entries
/// stay in place.
///
/// # Errors
/// [`AdapterError::UnsafeTarget`] for a tracked file without `allow_tracked` or
/// an escaping symlink, [`AdapterError::InvalidPayload`] for ambiguous markers,
/// otherwise git or I/O failures.
pub fn remove_from(
    repo_root: &Path,
    host: Host,
    opts: ApplyOptions,
) -> Result<InstallReport, AdapterError> {
    let Some(name) = instructions_file(host) else {
        return Ok(report_only(host, opts.dry_run));
    };
    let path = repo_root.join(name);
    let target = safe_target(repo_root, &path)?;
    let (marker, marker_target) = checked_backup(repo_root, &path, &target)?;
    retry_update(read_optional(&target)?, |snapshot| {
        guard(repo_root, &path, &target, opts)?;
        let mut report = InstallReport {
            dry_run: opts.dry_run,
            ..InstallReport::default()
        };
        let Some(original) = snapshot else {
            return Ok(Update::Done(report));
        };
        validate(original)?;
        let removed = remove(original);
        if removed == original {
            return Ok(Update::Done(report));
        }
        let backup = read_optional(&marker_target)?;
        let delete = backup.as_deref() == Some("") && removed.trim().is_empty();
        let restore = backup
            .as_deref()
            .is_some_and(|text| !text.is_empty() && text == removed);
        report.changed_files.push(path.clone());
        if delete || restore {
            report.changed_files.push(marker.clone());
        }
        if opts.dry_run {
            return Ok(Update::Done(report));
        }
        let replacement = (!delete).then_some(removed.as_str());
        match atomic_update(&target, snapshot, replacement, || Ok(()))? {
            Update::Done(()) => {
                if delete || restore {
                    fs::remove_file(&marker_target)?;
                }
                Ok(Update::Done(report))
            }
            Update::Retry(current) => Ok(Update::Retry(current)),
        }
    })
}
