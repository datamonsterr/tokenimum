//! `tokenimum` skill generation for fold-only mode (SPEC 6.12, ADR 0026).
//!
//! The skill lets the agent pull repository facts on demand. It lists read-only
//! commands only and makes no claim about effects.

use crate::writer::deny::refuse_tracked;
use crate::writer::{Update, atomic_update, read_optional, retry_update, safe_target};
use crate::{AdapterError, InstallReport};
use std::fs;
use std::path::{Path, PathBuf};
use tkm_proto::Host;

/// Options for [`install`] and [`uninstall`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct SkillOptions {
    /// Allow changing a git-tracked project skill file.
    pub allow_tracked: bool,
    /// Compute the change without writing.
    pub dry_run: bool,
}

const MARKER_PREFIX: &str = "<!-- tokenimum-skill version=";

/// Renders `SKILL.md` for `host`. Frontmatter comes first, as skill loaders require.
#[must_use]
pub fn render(host: Host) -> String {
    format!(
        "---\n\
         name: tokenimum\n\
         description: Read-only commands that print the repository facts tokenimum has recorded from earlier sessions.\n\
         ---\n\
         {MARKER_PREFIX}{version} host={host}; generated by tkm init, do not edit -->\n\
         \n\
         # tokenimum\n\
         \n\
         These commands only read; they change nothing. Run them in a shell.\n\
         \n\
         - `tkm status`: print the current repository status.\n\
         - `tkm status --json`: print the status as JSON.\n\
         - `tkm why <event|last>`: print an explanation of an action.\n\
         - `tkm facts --brief`: print active repository facts.\n\
         - `tkm skills --json`: print skill usage evidence as JSON.\n\
         - `tkm doctor`: print diagnostic information.\n",
        version = env!("CARGO_PKG_VERSION"),
        host = host.as_str(),
    )
}

/// Skill file path for `host`, or `None` when no skill directory is documented.
///
/// With `repo_root` the project directory is used, otherwise `agent_home`
/// (the harness's user configuration directory):
///
/// | Host | User scope | Project scope |
/// |---|---|---|
/// | Claude Code | `<agent_home>/skills` | `.claude/skills` |
/// | Codex | `<agent_home>/skills` | `.agents/skills` |
/// | Antigravity CLI | `<agent_home>/antigravity-cli/skills` | `.agents/skills` |
/// | Cursor | `<agent_home>/skills` | `.cursor/skills` |
/// | Kimi Code | `<agent_home>/skills` | `.kimi/skills` |
/// | Codewhale | `<agent_home>/skills` | `.codewhale/skills` |
/// | opencode | `<agent_home>/skills` | `.opencode/skills` |
/// | Pi | none | `.agents/skills` |
///
/// Evidence for these locations is recorded in ADR 0026.
#[must_use]
pub fn skill_path(host: Host, agent_home: &Path, repo_root: Option<&Path>) -> Option<PathBuf> {
    let skills = match (host, repo_root) {
        (Host::Claude, Some(repo)) => repo.join(".claude/skills"),
        (Host::Opencode, Some(repo)) => repo.join(".opencode/skills"),
        (Host::Pi | Host::Codex | Host::Agy, Some(repo)) => repo.join(".agents/skills"),
        (Host::Cursor, Some(repo)) => repo.join(".cursor/skills"),
        (Host::Kimi, Some(repo)) => repo.join(".kimi/skills"),
        (Host::Deepseek, Some(repo)) => repo.join(".codewhale/skills"),
        (Host::Agy, None) => agent_home.join("antigravity-cli/skills"),
        (
            Host::Claude
            | Host::Opencode
            | Host::Kimi
            | Host::Codex
            | Host::Cursor
            | Host::Deepseek,
            None,
        ) => agent_home.join("skills"),
        _ => return None,
    };
    Some(skills.join("tokenimum").join("SKILL.md"))
}

fn owned(text: &str) -> bool {
    text.lines().any(|line| line.starts_with(MARKER_PREFIX))
}

fn report_only(host: Host, dry_run: bool) -> InstallReport {
    InstallReport {
        changed_files: Vec::new(),
        instructions: vec![format!(
            "No verified skill directory for {} in this scope; run `tkm facts --brief` directly.",
            host.as_str()
        )],
        dry_run,
    }
}

/// Resolves the skill file, refusing a symlinked file and, in project scope, a
/// tracked one unless `opts.allow_tracked`. A project scope needs a git repository.
fn checked_path(
    path: &Path,
    scope: &Path,
    project: bool,
    opts: SkillOptions,
) -> Result<PathBuf, AdapterError> {
    if fs::symlink_metadata(path).is_ok_and(|meta| meta.file_type().is_symlink()) {
        return Err(AdapterError::UnsafeTarget {
            path: path.to_path_buf(),
            reason: "skill file is a symlink".to_owned(),
        });
    }
    let target = safe_target(scope, path)?;
    if project && !opts.allow_tracked && path.exists() {
        refuse_tracked(scope, path)?;
    }
    Ok(target)
}

/// Installs the skill under `agent_home`, or under `repo_root` for project scope.
///
/// Atomic, idempotent and honours `dry_run`. Refuses a symlinked `SKILL.md`, a
/// symlink that leaves the scope root, an existing `SKILL.md` that tokenimum did
/// not generate, and (project scope) a git-tracked file unless `allow_tracked`.
/// Hosts without a documented directory return a report-only result.
///
/// # Errors
/// [`AdapterError::UnsafeTarget`] for refusals, otherwise git or I/O failures.
pub fn install(
    host: Host,
    agent_home: &Path,
    repo_root: Option<&Path>,
    opts: SkillOptions,
) -> Result<InstallReport, AdapterError> {
    let Some(path) = skill_path(host, agent_home, repo_root) else {
        return Ok(report_only(host, opts.dry_run));
    };
    let target = checked_path(
        &path,
        repo_root.unwrap_or(agent_home),
        repo_root.is_some(),
        opts,
    )?;
    let content = render(host);
    retry_update(read_optional(&target)?, |snapshot| {
        let mut report = InstallReport {
            dry_run: opts.dry_run,
            ..InstallReport::default()
        };
        if snapshot.is_some_and(|text| !owned(text)) {
            return Err(AdapterError::UnsafeTarget {
                path: path.clone(),
                reason: "skill file was not generated by tokenimum".to_owned(),
            });
        }
        if snapshot == Some(content.as_str()) {
            return Ok(Update::Done(report));
        }
        report.changed_files.push(path.clone());
        if opts.dry_run {
            return Ok(Update::Done(report));
        }
        match atomic_update(&target, snapshot, Some(&content), || Ok(()))? {
            Update::Done(()) => Ok(Update::Done(report)),
            Update::Retry(current) => Ok(Update::Retry(current)),
        }
    })
}

/// Removes the skill file when it carries the tokenimum marker, plus its
/// `tokenimum` directory when that becomes empty. A file without the marker is
/// left alone; a symlinked or (project scope) tracked file is refused.
///
/// # Errors
/// [`AdapterError::UnsafeTarget`] for refusals, otherwise git or I/O failures.
pub fn uninstall(
    host: Host,
    agent_home: &Path,
    repo_root: Option<&Path>,
    opts: SkillOptions,
) -> Result<InstallReport, AdapterError> {
    let mut report = InstallReport {
        dry_run: opts.dry_run,
        ..InstallReport::default()
    };
    let Some(path) = skill_path(host, agent_home, repo_root) else {
        return Ok(report);
    };
    let target = checked_path(
        &path,
        repo_root.unwrap_or(agent_home),
        repo_root.is_some(),
        opts,
    )?;
    retry_update(read_optional(&target)?, |snapshot| {
        if !snapshot.is_some_and(owned) {
            return Ok(Update::Done(()));
        }
        report.changed_files = vec![path.clone()];
        if opts.dry_run {
            return Ok(Update::Done(()));
        }
        match atomic_update(&target, snapshot, None, || Ok(()))? {
            Update::Done(()) => {
                if let Some(directory) = target.parent()
                    && directory
                        .file_name()
                        .is_some_and(|name| name == "tokenimum")
                {
                    // Best effort: fails, and is kept, when the directory holds other files.
                    let _ = fs::remove_dir(directory);
                }
                Ok(Update::Done(()))
            }
            Update::Retry(current) => Ok(Update::Retry(current)),
        }
    })?;
    Ok(report)
}
